# bot/judges/vision_judge.py

def build_vision_prompt(user_text: str) -> str:
    """
    负责指导多模态视觉大模型如何解析图片。
    如果经常发代码报错截图，可以在这里加入：“如果是代码报错，请直接提取关键错误日志”。
    """
    prompt = (
        "请用客观且详细的语言来描述这张图片或表情包。如果是带有文字的表情包或截图，请把文字也读出来。\n"
        "如果是代码或报错日志截图，请尽可能准确地提取出关键的错误信息。\n\n"
        "【核心任务】：请务必判断这张图是“普通的实拍照片/风景/截图”，还是一张“表情包(Meme/梗图)”？\n"
        "如果你认为这是一张可以被收藏的表情包，请务必在你的回复最末尾独立一行输出：`[STICKER:情绪]`，情绪只能从【开心、难过、贴贴、生气】这四个词中选一个（选最贴近的）。\n"
        "如果这只是一般照片或截图，绝对不要输出这个标签！\n"
    )
    
    if user_text:
        prompt += f"\n【用户附带的文字说明】：{user_text}"
        
    return prompt