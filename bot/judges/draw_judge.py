def get_refine_prompt() -> str:
    """
    负责控制 AI 照片“质感”的终极精修提示词。
    优化目标：极度强化“手机摄像头”的物理光学特征和随手拍质感。
    """
    return (
        "这是一张完全由智能手机（如 iPhone 15 Pro）原生相机直接拍摄的照片。画面必须带有手机镜头的物理特征："
        "1. 视角：第一人称视角（POV）或手机前置摄像头自拍视角，画面必须有‘拿手机的人就在对面或自己拿手机’的空间临场感。"
        "2. 光学特征：带有一点手机广角镜头边缘的轻微拉伸畸变，可能有环境杂乱的光晕或真实的手机闪光灯反光（如果在暗处）。"
        "3. 质感：绝对没有经过任何美颜、精修或滤镜处理的原生生图（Raw mobile photo）质感，肤理真实。"
        "4. 构图：完全拒绝单反相机的唯美大景深和黄金比例构图。这就是一张在生活中随手掏出手机按下的快照，可以有一点点手抖的模糊、噪点或穿帮的日常杂乱背景。"
        "照片绝对不能看起来像是由 AI 生成的，必须呈现出 100% 真人持手机拍摄的粗糙却鲜活的生活质感。"
    )

def get_ref_image_prompt(description: str) -> str:
    """有参考垫图时的动作/场景变换提示词，加入手机视角约束"""
    return (
        f"请严格保持参考图中人物的五官特征、气质和基础设定，用【手机摄像头日常抓拍】的视角，"
        f"将其置入以下生活场景中，并根据场景自然调整动作与服装：{description}。"
        "要求：抛弃摆拍感，充满浓厚的生活日常氛围。"
    )

def get_base_gen_prompt(description: str) -> str:
    """无参考图时的基础生成提示词，从打底阶段就锁死手机镜头视角"""
    return (
        f"一张由手机摄像头拍摄的真实生活快照。人物及场景细节：{description}。"
        "要求：强烈的手机拍摄感，拒绝影棚打光，拒绝CG感，就像是直接从朋友圈相册里导出的原生照片。"
    )